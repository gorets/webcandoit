const shareLinkButton = document.querySelector('#share-link-button');
const shareFileButton = document.querySelector('#share-file-button');

shareLinkButton.addEventListener('click', async () => {
  try {
    await navigator.share({
      title: 'WebCanDoIt',
      text: 'Check out WebCanDoIt — see what your browser can do!',
      url: window.location.href,
    });
  } catch (err) {
    if (err.name !== 'AbortError') console.error('Failed to share.', err);
  }
});

shareFileButton.addEventListener('click', async () => {
  const file = new File(['Hello from the Web Share API demo!'], 'share-demo.txt', {
    type: 'text/plain',
  });

  if (typeof navigator.canShare !== 'function' || !navigator.canShare({ files: [file] })) {
    console.error('Sharing files is not supported on this device or browser.');
    return;
  }

  try {
    await navigator.share({
      title: 'Shared file',
      text: 'A small text file generated by the demo.',
      files: [file],
    });
  } catch (err) {
    if (err.name !== 'AbortError') console.error('Failed to share the file.', err);
  }
});
