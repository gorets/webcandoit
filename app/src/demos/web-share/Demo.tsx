import { useState } from 'react';

export default function WebShareDemo() {
  const [status, setStatus] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const shareLink = async () => {
    setError(null);
    setStatus(null);
    try {
      await navigator.share({
        title: 'WebCanDoIt',
        text: 'Check out WebCanDoIt — see what your browser can do!',
        url: window.location.href,
      });
      setStatus('Shared successfully.');
    } catch (err) {
      if (err instanceof DOMException && err.name === 'AbortError') {
        setStatus('Share was cancelled.');
        return;
      }
      setError(err instanceof Error ? err.message : 'Failed to share.');
    }
  };

  const shareFile = async () => {
    setError(null);
    setStatus(null);
    try {
      const file = new File(['Hello from the Web Share API demo!'], 'share-demo.txt', {
        type: 'text/plain',
      });

      if (typeof navigator.canShare !== 'function' || !navigator.canShare({ files: [file] })) {
        setError('Sharing files is not supported on this device or browser.');
        return;
      }

      await navigator.share({
        title: 'Shared file',
        text: 'A small text file generated by the demo.',
        files: [file],
      });
      setStatus('File shared successfully.');
    } catch (err) {
      if (err instanceof DOMException && err.name === 'AbortError') {
        setStatus('Share was cancelled.');
        return;
      }
      setError(err instanceof Error ? err.message : 'Failed to share the file.');
    }
  };

  return (
    <div>
      <p style={{ color: 'var(--text-dim)' }}>
        Opens the OS-native share sheet. On desktop browsers without a share target configured, this
        may show few or no destinations — that is expected.
      </p>
      <div style={{ display: 'flex', gap: '0.75rem', flexWrap: 'wrap' }}>
        <button type="button" onClick={shareLink}>
          Share this page
        </button>
        <button type="button" onClick={shareFile}>
          Share a file
        </button>
      </div>
      {status && (
        <p role="status" style={{ color: 'var(--accent)' }}>
          {status}
        </p>
      )}
      {error && (
        <p role="alert" style={{ color: 'var(--danger)' }}>
          {error}
        </p>
      )}
    </div>
  );
}
